function ghepGhiChuDon({ nguoiNhan = '', sdtNhan = '', gio = '', ghiChu = '' } = {}) {
  const dong = []
  const nn = [String(nguoiNhan).trim(), String(sdtNhan).trim()].filter(Boolean).join(' · ')
  if (nn) dong.push('Người nhận: ' + nn)
  if (String(gio).trim()) dong.push('Giờ giao: ' + String(gio).trim())
  if (String(ghiChu).trim()) dong.push(String(ghiChu).trim())
  return dong.join('\n')
}

function tachGhiChuDon(note) {
  const kq = { nguoiNhan: '', sdtNhan: '', gio: '', ghiChu: '' }
  const dong = String(note || '').split('\n')
  while (dong.length) {
    const d = dong[0].trim()
    let m
    if ((m = d.match(/^Người nhận:\s*(.*)$/))) {
      const [ten, sdt] = m[1].split(' · ')
      kq.nguoiNhan = (ten || '').trim(); kq.sdtNhan = (sdt || '').trim()
    } else if ((m = d.match(/^Giờ giao:\s*(.*)$/))) {
      kq.gio = m[1].trim()
    } else break
    dong.shift()
  }
  kq.ghiChu = dong.join('\n').trim()
  return kq
}

// ─── Caption mẫu hoa (mô tả sản phẩm) kiểu "tạp chí" ─────────
//   “Latte buổi sớm”                       ← biệt danh, dòng ĐẦU, trong ngoặc kép
//   Hồng Capuchino · giấy gói ánh vàng      ← thành phần, cách nhau bằng " · "
//   Ngọt ngào — tinh tế — rất ăn ảnh.       ← chữ khoá, cách nhau bằng " — "
//   Phù hợp tặng sinh nhật, lễ tốt nghiệp.
//   Hoa có đặt theo size                    ← mọi dòng khác (kích thước, tặng kèm…)
// Dòng đầu không phải biệt danh trong ngoặc kép → trả null, web hiện nguyên chữ shop gõ.
function tachCaption(desc) {
  const dong = String(desc || '').split('\n').map(s => s.trim()).filter(Boolean)
  const m = dong.length ? dong[0].match(/^[“"](.+)[”"]$/) : null
  if (!m) return null
  const kq = { bietDanh: m[1].trim(), thanhPhan: [], chuKhoa: '', phuHop: '', them: [] }
  for (const d of dong.slice(1)) {
    if (!kq.thanhPhan.length && d.includes('·')) kq.thanhPhan = d.split('·').map(s => s.trim()).filter(Boolean)
    else if (!kq.chuKhoa && d.includes('—')) kq.chuKhoa = d
    else if (!kq.phuHop && /^Phù hợp tặng/i.test(d)) kq.phuHop = d.replace(/\.$/, '')
    else kq.them.push(d)
  }
  return kq
}

// Chiều ngược của tachCaption: form Sản phẩm (admin) có ô riêng cho từng phần → ghép lại đúng khuôn trên.
//   thanhPhan / chuKhoa: chuỗi shop gõ, cách nhau bằng dấu phẩy (gõ · hay — cũng được).
// Thành phần chỉ có 1 thứ thì thêm " ·" ở cuối — không có dấu · thì tachCaption không nhận ra là thành phần.
function ghepCaption({ bietDanh = '', thanhPhan = '', chuKhoa = '', phuHop = '', them = '' } = {}) {
  // Biệt danh / thành phần / cảm giác / phù hợp tặng mỗi thứ đúng 1 dòng: chữ dán vào có xuống dòng thì gộp lại
  const dong1 = s => String(s || '').replace(/\s+/g, ' ').trim()
  const tach = (s, dau) => dong1(s).split(dau).map(x => x.trim()).filter(Boolean)
  const bd = dong1(bietDanh).replace(/^[“"]+|[”"]+$/g, '').trim()
  const tp = tach(thanhPhan, /[,·]/)
  // cảm giác: dấu · cũng là dấu tách — để nguyên thì dòng này bị web đọc nhầm thành "thành phần"
  const ck = tach(dong1(chuKhoa).replace(/[.。]+$/, ''), /[,—–·]/)
  const ph = dong1(phuHop).replace(/^phù hợp tặng\s*/i, '').replace(/\.+$/, '').trim()
  const dong = []
  if (bd) dong.push(`“${bd}”`)
  if (tp.length) dong.push(tp.join(' · ') + (tp.length === 1 && bd ? ' ·' : ''))
  if (ck.length) dong.push(ck.join(' — ') + '.')
  if (ph) dong.push(`Phù hợp tặng ${ph}.`)
  const t = String(them || '').trim()
  if (t) dong.push(t)
  return dong.join('\n')
}

// ─── Hiển thị giá (giá lưu dạng CHỮ tự do) — dùng chung web + admin (03/10/2026) ─────
//   "600000" / "600,000đ" / "600.000 đ"   → "600.000đ"
//   "Từ 50000"                           → "Từ 50.000đ"  (trước: "50.000đ" — mất chữ "Từ")
//   "Từ 300.000 - 500.000"               → giữ nguyên    (trước: dồn mọi chữ số thành "300.000.500.000đ")
//   "Từ 2xx", "Liên hệ", "Liên hệ 0352…" → giữ nguyên   (số bắt đầu bằng 0 = SĐT, không phải tiền)
function hienGia(raw) {
  const s = String(raw ?? '').trim()
  if (/^[\d.,\s]+(đ|d|vnđ|vnd)?$/i.test(s)) {            // chỉ là MỘT số tiền
    const n = parseInt(s.replace(/\D/g, ''), 10)
    return n >= 1000 ? n.toLocaleString('vi-VN') + 'đ' : s
  }
  // Có chữ: chỉ chấm hàng nghìn cho số TRẦN ≥ 4 chữ số (không bắt đầu bằng 0), chữ còn lại để nguyên
  return s.replace(/(^|[^\d.,])([1-9]\d{3,})(?![\d.,a-zA-Z])(\s*(?:vnđ|đ))?/gi,
    (_, truoc, so) => truoc + Number(so).toLocaleString('vi-VN') + 'đ')
}
// Số tiền ĐẦU TIÊN trong giá ("Từ 300.000 - 500.000" → 300000; "Từ 2xx" → 2) — để tìm giá thấp nhất
function soGiaDau(raw) {
  const m = String(raw ?? '').match(/(?:^|[^\d.,])([1-9][\d.,]*)/)   // số bắt đầu bằng 0 (SĐT) không tính
  return m ? parseInt(m[1].replace(/\D/g, ''), 10) : NaN
}

