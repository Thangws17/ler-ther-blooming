// Chặn HTML lạ trong dữ liệu người dùng nhập trước khi nhét vào trang
function esc(s) {
  return String(s ?? '').replace(/[&<>"']/g, c => ({ '&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;' }[c]))
}

// Chuỗi nằm TRONG onclick="fn('…')" thì esc() chưa đủ: trình duyệt đổi &#39; ngược lại
// thành dấu ' TRƯỚC khi chạy lệnh → chuỗi bị cắt, phần sau thành lệnh lạ (test-bao-mat bắt).
// jsAttr: thoát lớp JS (dấu \ và ') rồi mới thoát lớp HTML.
function jsAttr(s) {
  return esc(String(s ?? '').replace(/\\/g, '\\\\').replace(/'/g, "\\'"))
}

// Link do shop nhập (Facebook, TikTok…): chỉ nhận http/https. Gõ thiếu "https://"
// ("facebook.com/ler") thì tự thêm; còn "javascript:…" hay chữ lạ → bỏ (trả '').
function linkAnToan(url) {
  const s = String(url ?? '').trim()
  if (!s) return ''
  if (/^https?:\/\//i.test(s)) return s
  if (/^[a-z0-9-]+(\.[a-z0-9-]+)+(\/\S*)?$/i.test(s)) return 'https://' + s
  return ''
}

// Bỏ dấu tiếng Việt để tìm kiếm dễ tính: gõ "hoa hong" vẫn ra "Hoa Hồng", "chi thoa" ra "Chị Thoa"
function noAccent(s) {
  return String(s ?? '').toLowerCase()
    .normalize('NFD').replace(/[\u0300-\u036f]/g, '')   // dải dấu thanh/mũ Unicode
    .replace(/đ/g, 'd').trim()
}

// Bộ sưu tập (BST) có đang hiện trên web khách không: tắt tay, hoặc chưa tới / đã qua ngày hẹn.
// Admin báo "đang hiện / đang ẩn" và web khách quyết định hiện bộ nào đều dựa vào ĐÚNG hàm này
// (trước 11/10/2026 viết 2 bản ở main.js + admin, phải nhớ sửa cả hai).
function bstDangHien(c, homNay = new Date().toLocaleDateString('sv-SE')) {
  if (!c || !c.active) return false
  if (c.start_date && c.start_date > homNay) return false
  if (c.end_date   && c.end_date   < homNay) return false
  return true
}

